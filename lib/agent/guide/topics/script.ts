export const scriptTopic = `# The script

The script is not prose. It is **one line per caption**, each line a beat the picture shows.

## The format
\`\`\`
If the whole city goes dark
and you live on the *fourteenth floor*,
the clock starts now.

Meet *Maya*.
She's *twenty-four*.
\`\`\`
- One line = one caption = one voice clip. Never a paragraph.
- \`*word*\` marks the key word: at most one per line, sometimes none. What the mark does is the style's (a whole-line colour in Story Scene, the serif word in Presenter, the accent word in System and Documentary).
- A blank line ends a scene (the storyboard may still split or join them).
- 3 to 8 words a line. A longer line becomes two.

## Rules every reference follows
1. Short declaratives. "The power dies." not "When the power eventually went out…".
2. Present tense, even for the past: it puts the viewer inside it.
3. One fact per line. Two ideas are two lines.
4. Specific numbers when you have them — 6:42 PM, 80 litres, $41 — and **never one you don't**. A real person's or product's numbers come from the user or a source.
5. Every line names a thing that can be drawn. A line with no picture is cut.
6. Second person for stories ("you"), imperative for tutorials, never first person.
7. No throat-clearing: the first line is the situation. Never "In this video".

## Structure
- Hook (0–3 s): the situation, stated flat.
- Body: one line per beat, each with its picture.
- Turn: one line — "But.", "Then.", "Except." — the page flips.
- Payoff: the strongest picture, the biggest word.
- End (held ~1.5 s): a cliffhanger for a serial, or the call to action.
Each style's brief gives its own beat map on top of this.

## Pace
Read-aloud pace is about 2.5 words a second — use it only to estimate length before the voice exists. The real times come from the voice clips.`
